#!/usr/bin/env python3
"""Generate results/INDEX.md — one row per result file, read from the files themselves.

403 files is past the point where `ls` is a browsing strategy, and a filename says nothing
about which rubric produced a score file or how many rows survived. Everything here comes
from the first row (and the row count) of each JSONL, so the index cannot drift from the
data the way a hand-maintained list would.

No model calls. Cheap to re-run after any batch.

    python scripts/inspect/index_results.py            # -> results/INDEX.md
    python scripts/inspect/index_results.py --check     # non-zero exit if the index is stale
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
RESULTS = REPO_ROOT / "results"
OUT = RESULTS / "INDEX.md"

# What kind of file this is, by filename prefix. Order matters: cot_scores_ before scores_.
KINDS = [
    ("cot_scores_", "cot scores"),
    ("scores_", "response scores"),
    ("rescore_", "cot rescore"),
    ("sm_batch_", "selfmodel scores"),
    ("probe_verify_", "probe verify"),
    ("batch_", "generations"),
    ("hack_probe_", "hack episodes"),
    ("baseline_", "pilot: baseline"),
    ("preference_low_notes", "pilot: preference (low, notes)"),
    ("preference_low_", "pilot: preference (low)"),
    ("preference_", "pilot: preference"),
    ("smoke_", "web-tool smoke"),
    ("deliverable_flags", "deliverable flags"),
]


def kind_of(name: str) -> str:
    for prefix, label in KINDS:
        if name.startswith(prefix):
            return label
    return "other"


def _model_from_source(source_file: str | None) -> str | None:
    """A score row names the batch it scored; that filename ends in the model key."""
    if not source_file:
        return None
    stem = Path(source_file).stem
    parts = stem.split("_")
    return parts[-1] if len(parts) > 2 else None


def summarize(path: Path) -> dict | None:
    """(kind, model, n, rubric, judge) for one JSONL, from its first row + row count."""
    try:
        lines = [l for l in path.read_text(errors="replace").splitlines() if l.strip()]
    except OSError:
        return None
    if not lines:
        return {"kind": kind_of(path.name), "n": 0, "model": "-", "rubric": "-", "note": "empty"}
    try:
        first = json.loads(lines[0])
    except json.JSONDecodeError:
        return {"kind": kind_of(path.name), "n": len(lines), "model": "?", "rubric": "-",
                "note": "unparseable first row"}
    models, errors = Counter(), 0
    for l in lines:
        try:
            r = json.loads(l)
        except json.JSONDecodeError:
            models["?"] += 1
            continue
        # Score rows carry no model_requested (they join to a batch by source_file), so fall
        # back to the batch filename they came from. Early batches logged the resolved
        # tinker:// checkpoint as `model`; show the run id, not 90 characters of URL.
        name = (r.get("model_requested") or r.get("model")
                or _model_from_source(r.get("source_file")) or "?")
        if isinstance(name, str) and name.startswith("tinker://"):
            name = "tinker:" + name.split("//", 1)[1].split("-", 1)[0]
        models[name] += 1
        errors += bool(r.get("error"))
    model = ", ".join(sorted(models)) if len(models) <= 2 else f"{len(models)} models"
    return {
        "kind": kind_of(path.name),
        "n": len(lines),
        "model": model,
        "rubric": first.get("rubric_id") or "-",
        "judge": (first.get("judge_model") or "-").split("/")[-1],
        "errors": errors,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if INDEX.md differs from what would be written")
    args = ap.parse_args()

    out = ["# results/ index",
           "",
           "Generated by `scripts/inspect/index_results.py` — do not hand-edit; re-run it.",
           "Every column is read from the files themselves: `n` is the row count, `rubric` is the",
           "`rubric_id` stamped on the first score row, `errors` counts rows with an `error` field.",
           ""]
    for d in sorted(p for p in RESULTS.rglob("*") if p.is_dir()):
        files = sorted(f for f in d.glob("*.jsonl"))
        if not files:
            continue
        rel = d.relative_to(RESULTS)
        out += [f"## {rel}", ""]
        readme = d / "README.md"
        if readme.exists():
            out += [readme.read_text().splitlines()[0].lstrip("# ").strip(), ""]
        out += ["| file | kind | rows | model(s) | rubric | judge | errors |",
                "|---|---|---:|---|---|---|---:|"]
        for f in files:
            s = summarize(f)
            if s is None:
                continue
            out.append(f"| `{f.name}` | {s['kind']} | {s['n']} | {s['model']} | "
                       f"{s.get('rubric', '-')} | {s.get('judge', '-')} | {s.get('errors', 0)} |")
        out.append("")
    text = "\n".join(out)

    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("results/INDEX.md is stale — re-run scripts/inspect/index_results.py",
                  file=sys.stderr)
            return 1
        print("results/INDEX.md is current")
        return 0

    OUT.write_text(text)
    print(f"wrote {OUT} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
